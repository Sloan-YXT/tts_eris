def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--voice-id", default="eris_test_002", help="使用的音色 ID")
    args = parser.parse_args()

    voice_id = args.voice_id
    total = len(TESTS)
    ok = 0
    errors = 0

    print(f"音色: {voice_id}  总计: {total} 句")
    print(f"输出目录: {OUT_DIR}")
    print("-" * 60)

    for i, (text, emotion) in enumerate(TESTS, start=1):
        out_path = OUT_DIR / f"output_{i:03d}_{emotion}.wav"

        if out_path.exists():
            print(f"  [{i:03d}/{total}] SKIP  {out_path.name}")
            ok += 1
            continue

        try:
            resp = httpx.post(
                API_URL,
                json={"text": text, "voice_id": voice_id},
                timeout=120.0,
            )
            resp.raise_for_status()
            out_path.write_bytes(resp.content)
            size_kb = len(resp.content) / 1024
            print(f"  [{i:03d}/{total}] OK  {out_path.name}  ({size_kb:.0f}KB)  {text[:28]}...")
            ok += 1
        except httpx.ConnectError:
            print(f"  [{i:03d}/{total}] ERROR 无法连接 {API_URL}，请确认 run.py 已启动")
            sys.exit(1)
        except Exception as e:
            print(f"  [{i:03d}/{total}] ERROR {e}")
            errors += 1

    print("-" * 60)
    print(f"完成: {ok} 成功  {errors} 失败")


if __name__ == "__main__":
    main()
