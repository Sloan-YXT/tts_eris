def main() -> None:
    import scipy.io.wavfile as wavfile
    from style_bert_vits2.tts_model import TTSModel
    from style_bert_vits2.constants import Languages

    OUT_DIR.mkdir(exist_ok=True)

    # 既存ファイルを削除
    for old in OUT_DIR.glob("*.wav"):
        old.unlink()

    # モデル読み込み
    models = sorted(ASSETS_DIR.glob("eris_e*_s*.safetensors"), key=lambda p: p.stat().st_mtime)
    if not models:
        print(f"モデルが見つかりません: {ASSETS_DIR}")
        sys.exit(1)
    model_path = models[-1]
    config_path = ASSETS_DIR / "config.json"
    style_vec_path = ASSETS_DIR / "style_vectors.npy"

    print(f"モデル: {model_path.name}")
    print(f"テスト: {len(TESTS)} 件")
    print(f"出力先: {OUT_DIR}\n")

    t0 = time.time()
    model = TTSModel(
        model_path=model_path,
        config_path=config_path,
        style_vec_path=style_vec_path,
        device="cuda",
    )
    print(f"モデル読み込み完了 ({time.time() - t0:.1f}s)\n")

    total = len(TESTS)
    counts: dict[str, int] = {e: 0 for e in EMOTION_PARAMS}
    t_start = time.time()

    for i, (text, emotion) in enumerate(TESTS, 1):
        params = EMOTION_PARAMS[emotion]
        out_path = OUT_DIR / f"{i:03d}_{emotion}.wav"

        t0 = time.time()
        sr, audio = model.infer(
            text=text,
            language=Languages.JP,
            speaker_id=0,
            style=emotion,
            style_weight=params["style_weight"],
            sdp_ratio=params["sdp_ratio"],
            noise=params["noise"],
            noise_w=params["noise_w"],
            length=params["length"],
        )
        dt = time.time() - t0
        duration = len(audio) / sr

        wavfile.write(str(out_path), sr, audio)
        counts[emotion] += 1
        print(f"  [{i:3d}/{total}] {emotion:10s} | {duration:4.1f}s | {dt:.2f}s | {text[:35]}...")

    elapsed = time.time() - t_start
    print(f"\n{'=' * 60}")
    print(f"  完了! {total} 件 ({elapsed:.0f}s)")
    print(f"{'=' * 60}")
    for emo, n in counts.items():
        print(f"  {emo:12s}: {n}")
    print(f"  出力先: {OUT_DIR}")


if __name__ == "__main__":
    main()
