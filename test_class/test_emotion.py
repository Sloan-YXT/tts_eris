def main() -> None:
    total = len(TESTS)
    ok = 0
    errors = 0

    print(f"テスト開始: {total} 件  →  {OUT_DIR}")
    print("-" * 60)

    for i, (text, emotion) in enumerate(TESTS, start=1):
        out_path = OUT_DIR / f"output_wav_{i:03d}_{emotion}.wav"

        # 既存ファイルをスキップ
        if out_path.exists():
            print(f"  [{i:02d}/{total}] SKIP  {out_path.name}")
            ok += 1
            continue

        try:
            resp = httpx.post(API_URL, json={"text": text}, timeout=120.0)
            resp.raise_for_status()
            out_path.write_bytes(resp.content)
            size_kb = len(resp.content) / 1024
            print(f"  [{i:02d}/{total}] OK    {out_path.name}  ({size_kb:.0f} KB)  {text[:30]}...")
            ok += 1
        except httpx.ConnectError:
            print(f"  [{i:02d}/{total}] ERROR 无法连接 {API_URL}，请先启动 run_with_class.py")
            sys.exit(1)
        except Exception as e:
            print(f"  [{i:02d}/{total}] ERROR {e}  text={text[:30]}")
            errors += 1

    print("-" * 60)
    print(f"完了: {ok} 成功  {errors} 失败")


if __name__ == "__main__":
    main()
